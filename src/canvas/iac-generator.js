/**
 * Enterprise Multi-Cloud Infrastructure as Code (IaC) Synthesis Engine
 * Compiles visual graph topologies into Terraform, Helm Charts, CloudFormation, Docker, and Mermaid.js.
 */

export class IaCGenerator {
  /**
   * Generates Terraform (HCL)
   */
  static generateTerraform(nodes, connections) {
    let tf = `# =========================================================================\n`;
    tf += `# Terraform Architecture Definition — Generated by OmniFlow Studio (WebMCP)\n`;
    tf += `# Target: AWS Cloud Provider with High-Availability VPC & Zero-Trust IAM\n`;
    tf += `# =========================================================================\n\n`;

    tf += `terraform {\n  required_version = ">= 1.6.0"\n  required_providers {\n    aws = {\n      source  = "hashicorp/aws"\n      version = "~> 5.30"\n    }\n  }\n}\n\n`;
    tf += `provider "aws" {\n  region = "us-east-1"\n  default_tags {\n    tags = {\n      ManagedBy   = "OmniFlow-WebMCP"\n      Environment = "production"\n    }\n  }\n}\n\n`;

    tf += `# --- Core VPC & Network Subnets ---\n`;
    tf += `resource "aws_vpc" "main" {\n  cidr_block           = "10.0.0.0/16"\n  enable_dns_hostnames = true\n  enable_dns_support   = true\n  tags = { Name = "omniflow-vpc" }\n}\n\n`;

    nodes.forEach(node => {
      const cleanId = node.id.replace(/[^a-zA-Z0-9_]/g, '_');
      const cleanLabel = node.label.replace(/"/g, '\\"');
      const reps = node.replicas || 1;

      switch (node.type) {
        case 'gateway':
          tf += `# API Gateway: ${cleanLabel}\n`;
          tf += `resource "aws_apigatewayv2_api" "${cleanId}" {\n  name          = "${cleanLabel}"\n  protocol_type = "HTTP"\n  cors_configuration {\n    allow_origins = ["*"]\n    allow_methods = ["GET", "POST", "PUT", "DELETE", "OPTIONS"]\n    allow_headers = ["*"]\n  }\n}\n\n`;
          break;

        case 'gpu_cluster':
          tf += `# NVIDIA H100 GPU Cluster: ${cleanLabel}\n`;
          tf += `resource "aws_eks_node_group" "${cleanId}" {\n  cluster_name    = "omniflow-ai-cluster"\n  node_group_name = "${cleanId}-h100"\n  node_role_arn   = "arn:aws:iam::123456789012:role/EKSGpuNodeRole"\n  subnet_ids      = ["subnet-gpu-1a", "subnet-gpu-1b"]\n  instance_types  = ["p5.48xlarge"] # 8x NVIDIA H100 SXM5 GPUs\n  scaling_config {\n    desired_size = ${reps}\n    max_size     = 8\n    min_size     = 1\n  }\n}\n\n`;
          break;

        case 'service':
          tf += `# Microservice ECS Fargate: ${cleanLabel}\n`;
          tf += `resource "aws_ecs_service" "${cleanId}" {\n  name            = "${cleanId}"\n  cluster         = "arn:aws:ecs:us-east-1:123456789012:cluster/omniflow-cluster"\n  task_definition = "arn:aws:ecs:us-east-1:123456789012:task-definition/${cleanId}:1"\n  desired_count   = ${reps}\n  launch_type     = "FARGATE"\n  network_configuration {\n    subnets          = ["subnet-1a", "subnet-1b"]\n    assign_public_ip = false\n  }\n}\n\n`;
          break;

        case 'database':
          tf += `# Aurora PostgreSQL Multi-AZ Cluster: ${cleanLabel}\n`;
          tf += `resource "aws_rds_cluster" "${cleanId}" {\n  cluster_identifier      = "${cleanId}-aurora"\n  engine                  = "aurora-postgresql"\n  engine_version          = "16.1"\n  availability_zones      = ["us-east-1a", "us-east-1b", "us-east-1c"]\n  database_name           = "app_db"\n  master_username         = "omni_admin"\n  master_password         = "var.db_password"\n  backup_retention_period = 14\n  preferred_backup_window = "03:00-04:00"\n  storage_encrypted       = true\n}\n\n`;
          break;

        case 'cache':
          tf += `# ElastiCache Redis Cluster: ${cleanLabel}\n`;
          tf += `resource "aws_elasticache_replication_group" "${cleanId}" {\n  replication_group_id       = "${cleanId}"\n  description                = "Redis cluster for ${cleanLabel}"\n  node_type                  = "cache.r6g.large"\n  num_cache_clusters         = ${reps > 1 ? reps : 2}\n  automatic_failover_enabled = true\n  at_rest_encryption_enabled = true\n  transit_encryption_enabled = true\n}\n\n`;
          break;

        case 'queue':
          tf += `# Amazon Managed Kafka (MSK): ${cleanLabel}\n`;
          tf += `resource "aws_msk_cluster" "${cleanId}" {\n  cluster_name           = "${cleanId}"\n  kafka_version          = "3.5.1"\n  number_of_broker_nodes = 3\n  broker_node_group_info {\n    instance_type   = "kafka.m5.large"\n    client_subnets  = ["subnet-1a", "subnet-1b", "subnet-1c"]\n    security_groups = ["sg-kafka"]\n  }\n  encryption_info {\n    encryption_in_transit {\n      client_broker = "TLS"\n    }\n  }\n}\n\n`;
          break;

        case 'vector_db':
          tf += `# Milvus Distributed Vector Store on EKS: ${cleanLabel}\n`;
          tf += `resource "helm_release" "${cleanId}" {\n  name       = "milvus-distributed"\n  repository = "https://milvus-io.github.io/milvus-helm/"\n  chart      = "milvus"\n  namespace  = "ai-inference"\n  set {\n    name  = "cluster.enabled"\n    value = "true"\n  }\n}\n\n`;
          break;

        default:
          tf += `# Cloud Resource: ${cleanLabel} (${node.type})\n`;
          break;
      }
    });

    return tf;
  }

  /**
   * Generates Kubernetes Helm Chart (YAML)
   */
  static generateHelmChart(nodes, connections) {
    let helm = `# =========================================================================\n`;
    helm += `# Kubernetes Helm Chart: values.yaml — Generated by OmniFlow Studio\n`;
    helm += `# =========================================================================\n\n`;

    helm += `global:\n  environment: production\n  domain: omniflow.internal\n  imageRegistry: ghcr.io/omniflow\n\n`;

    nodes.forEach(node => {
      const cleanId = node.id.replace(/[^a-zA-Z0-9_]/g, '-').toLowerCase();
      const isGpu = node.type === 'gpu_cluster';

      helm += `${cleanId}:\n  enabled: true\n  replicaCount: ${node.replicas || (isGpu ? 1 : 3)}\n  image:\n    repository: ghcr.io/omniflow/${cleanId}\n    tag: "latest"\n    pullPolicy: IfNotPresent\n  service:\n    type: ClusterIP\n    port: 8080\n  resources:\n`;

      if (isGpu) {
        helm += `    limits:\n      nvidia.com/gpu: 8\n      memory: 128Gi\n      cpu: 64\n    requests:\n      nvidia.com/gpu: 8\n      memory: 64Gi\n      cpu: 32\n`;
      } else {
        helm += `    limits:\n      cpu: "1000m"\n      memory: "1024Mi"\n    requests:\n      cpu: "250m"\n      memory: "256Mi"\n`;
      }

      helm += `  autoscaling:\n    enabled: true\n    minReplicas: 2\n    maxReplicas: 10\n    targetCPUUtilizationPercentage: 75\n\n`;
    });

    return helm;
  }

  /**
   * Generates AWS CloudFormation (YAML)
   */
  static generateCloudFormation(nodes, connections) {
    let cf = `AWSTemplateFormatVersion: '2010-09-09'\nDescription: 'OmniFlow Studio Generated CloudFormation Production Stack'\n\nParameters:\n  Environment:\n    Type: String\n    Default: production\n\nResources:\n`;

    nodes.forEach(node => {
      const cleanId = node.id.replace(/[^a-zA-Z0-9]/g, '');
      cf += `  ${cleanId}Service:\n    Type: AWS::ECS::Service\n    Properties:\n      ServiceName: ${cleanId}\n      DesiredCount: ${node.replicas || 2}\n      LaunchType: FARGATE\n      TaskDefinition: !Ref ${cleanId}TaskDefinition\n\n`;
    });

    return cf;
  }

  /**
   * Generates Docker Compose (YAML)
   */
  static generateDockerCompose(nodes, connections) {
    let dc = `version: '3.8'\n\nservices:\n`;

    nodes.forEach(node => {
      const cleanId = node.id.replace(/[^a-zA-Z0-9_]/g, '-').toLowerCase();

      switch (node.type) {
        case 'gateway':
          dc += `  ${cleanId}:\n    image: kong:3.4-alpine\n    ports:\n      - "8000:8000"\n    environment:\n      KONG_DATABASE: "off"\n    networks:\n      - omniflow-net\n\n`;
          break;

        case 'gpu_cluster':
          dc += `  ${cleanId}:\n    image: vllm/vllm-openai:latest\n    deploy:\n      resources:\n        reservations:\n          devices:\n            - driver: nvidia\n              count: all\n              capabilities: [gpu]\n    environment:\n      MODEL: "meta-llama/Llama-3-70b"\n      TENSOR_PARALLEL_SIZE: 8\n    networks:\n      - omniflow-net\n\n`;
          break;

        case 'service':
        case 'serverless':
          dc += `  ${cleanId}:\n    build:\n      context: ./${cleanId}\n    environment:\n      NODE_ENV: production\n    restart: always\n    networks:\n      - omniflow-net\n\n`;
          break;

        case 'database':
          dc += `  ${cleanId}:\n    image: postgres:16-alpine\n    environment:\n      POSTGRES_DB: app_db\n      POSTGRES_PASSWORD: secure_pass_2026\n    volumes:\n      - pgdata_${cleanId}:/var/lib/postgresql/data\n    networks:\n      - omniflow-net\n\n`;
          break;

        case 'cache':
          dc += `  ${cleanId}:\n    image: redis:7.2-alpine\n    command: redis-server --appendonly yes\n    networks:\n      - omniflow-net\n\n`;
          break;

        default:
          dc += `  ${cleanId}:\n    image: alpine:latest\n    command: ["sleep", "infinity"]\n    networks:\n      - omniflow-net\n\n`;
          break;
      }
    });

    dc += `networks:\n  omniflow-net:\n    driver: bridge\n\nvolumes:\n`;
    nodes.filter(n => n.type === 'database').forEach(n => {
      const cleanId = n.id.replace(/[^a-zA-Z0-9_]/g, '-').toLowerCase();
      dc += `  pgdata_${cleanId}:\n`;
    });

    return dc;
  }

  /**
   * Generates TypeScript Architecture Object
   */
  static generateTypeScript(nodes, connections) {
    const data = {
      version: '3.0.0',
      generatedAt: new Date().toISOString(),
      generator: 'OmniFlow WebMCP Enterprise Engine',
      topology: {
        totalNodes: nodes.length,
        totalConnections: connections.length,
        nodes: nodes.map(n => ({
          id: n.id,
          label: n.label,
          type: n.type,
          replicas: n.replicas || 1,
          status: n.status,
          telemetry: { cpu: n.cpu, memory: n.memory }
        })),
        connections: connections.map(c => ({
          id: c.id,
          from: c.from,
          to: c.to,
          protocol: c.protocol,
          latency: c.latency,
          throughput: c.throughput
        }))
      }
    };

    return `export const productionArchitecture = ${JSON.stringify(data, null, 2)};\n`;
  }
}
