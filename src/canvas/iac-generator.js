/**
 * Infrastructure as Code (IaC) Synthesis Engine
 * Transforms active canvas graph topology into production-ready configs.
 */

export class IaCGenerator {
  /**
   * Generates Terraform (HCL)
   */
  static generateTerraform(nodes, connections) {
    let tf = `# =========================================================================\n`;
    tf += `# Terraform Architecture Definition — Generated by OmniFlow Studio (WebMCP)\n`;
    tf += `# Target: AWS Cloud Provider with High-Availability VPC\n`;
    tf += `# =========================================================================\n\n`;

    tf += `terraform {\n  required_version = ">= 1.5.0"\n  required_providers {\n    aws = {\n      source  = "hashicorp/aws"\n      version = "~> 5.0"\n    }\n  }\n}\n\n`;
    tf += `provider "aws" {\n  region = "us-east-1"\n  default_tags {\n    tags = {\n      ManagedBy   = "OmniFlow-WebMCP"\n      Environment = "production"\n    }\n  }\n}\n\n`;

    tf += `# --- Core VPC & Network Subnets ---\n`;
    tf += `resource "aws_vpc" "main" {\n  cidr_block           = "10.0.0.0/16"\n  enable_dns_hostnames = true\n  enable_dns_support   = true\n  tags = { Name = "omniflow-vpc" }\n}\n\n`;

    nodes.forEach(node => {
      const cleanId = node.id.replace(/[^a-zA-Z0-9_]/g, '_');
      const cleanLabel = node.label.replace(/"/g, '\\"');

      switch (node.type) {
        case 'gateway':
          tf += `# API Gateway: ${cleanLabel}\n`;
          tf += `resource "aws_apigatewayv2_api" "${cleanId}" {\n  name          = "${cleanLabel}"\n  protocol_type = "HTTP"\n  cors_configuration {\n    allow_origins = ["*"]\n    allow_methods = ["GET", "POST", "PUT", "DELETE", "OPTIONS"]\n    allow_headers = ["*"]\n  }\n}\n\n`;
          break;

        case 'service':
          tf += `# Microservice ECS Fargate: ${cleanLabel}\n`;
          tf += `resource "aws_ecs_service" "${cleanId}" {\n  name            = "${cleanId}"\n  cluster         = "arn:aws:ecs:us-east-1:123456789012:cluster/omniflow-cluster"\n  task_definition = "arn:aws:ecs:us-east-1:123456789012:task-definition/${cleanId}:1"\n  desired_count   = 3\n  launch_type     = "FARGATE"\n  network_configuration {\n    subnets          = ["subnet-1a", "subnet-1b"]\n    assign_public_ip = false\n  }\n}\n\n`;
          break;

        case 'database':
          tf += `# PostgreSQL RDS Instance: ${cleanLabel}\n`;
          tf += `resource "aws_db_instance" "${cleanId}" {\n  identifier             = "${cleanId}"\n  engine                 = "postgres"\n  engine_version         = "16.1"\n  instance_class         = "db.r6g.xlarge"\n  allocated_storage      = 100\n  max_allocated_storage  = 1000\n  multi_az               = true\n  storage_encrypted      = true\n  skip_final_snapshot    = false\n  publicly_accessible    = false\n}\n\n`;
          break;

        case 'cache':
          tf += `# Redis Cluster: ${cleanLabel}\n`;
          tf += `resource "aws_elasticache_replication_group" "${cleanId}" {\n  replication_group_id = "${cleanId}"\n  description          = "Redis cluster for ${cleanLabel}"\n  node_type            = "cache.r6g.large"\n  num_cache_clusters   = 3\n  automatic_failover_enabled = true\n  at_rest_encryption_enabled = true\n  transit_encryption_enabled = true\n}\n\n`;
          break;

        case 'queue':
          tf += `# Managed Kafka (MSK) Cluster: ${cleanLabel}\n`;
          tf += `resource "aws_msk_cluster" "${cleanId}" {\n  cluster_name           = "${cleanId}"\n  kafka_version          = "3.5.1"\n  number_of_broker_nodes = 3\n  broker_node_group_info {\n    instance_type   = "kafka.m5.large"\n    client_subnets  = ["subnet-1a", "subnet-1b", "subnet-1c"]\n    security_groups = ["sg-kafka"]\n  }\n  encryption_info {\n    encryption_in_transit {\n      client_broker = "TLS"\n    }\n  }\n}\n\n`;
          break;

        case 'ai_model':
          tf += `# Bedrock / SageMaker Model Endpoint: ${cleanLabel}\n`;
          tf += `resource "aws_sagemaker_endpoint" "${cleanId}" {\n  name                 = "${cleanId}"\n  endpoint_config_name = "omniflow-llm-config"\n  tags = {\n    Model = "${cleanLabel}"\n  }\n}\n\n`;
          break;

        case 'blob_store':
          tf += `# S3 Secure Storage Bucket: ${cleanLabel}\n`;
          tf += `resource "aws_s3_bucket" "${cleanId}" {\n  bucket = "omniflow-${cleanId}-data"\n}\n`;
          tf += `resource "aws_s3_bucket_server_side_encryption_configuration" "${cleanId}_enc" {\n  bucket = aws_s3_bucket.${cleanId}.id\n  rule {\n    apply_server_side_encryption_by_default {\n      sse_algorithm = "AES256"\n    }\n  }\n}\n\n`;
          break;

        default:
          tf += `# Generic Cloud Resource: ${cleanLabel} (${node.type})\n`;
          break;
      }
    });

    return tf;
  }

  /**
   * Generates Docker Compose (YAML)
   */
  static generateDockerCompose(nodes, connections) {
    let dc = `# =========================================================================\n`;
    dc += `# Docker Compose Environment — Generated by OmniFlow Studio (WebMCP)\n`;
    dc += `# =========================================================================\n\n`;
    dc += `version: '3.8'\n\nservices:\n`;

    nodes.forEach(node => {
      const cleanId = node.id.replace(/[^a-zA-Z0-9_]/g, '-').toLowerCase();

      switch (node.type) {
        case 'gateway':
          dc += `  ${cleanId}:\n    image: kong:3.4-alpine\n    container_name: ${cleanId}\n    ports:\n      - "8000:8000"\n      - "8443:8443"\n    environment:\n      KONG_DATABASE: "off"\n      KONG_DECLARATIVE_CONFIG: /etc/kong/kong.yml\n    networks:\n      - omniflow-net\n\n`;
          break;

        case 'service':
        case 'serverless':
          dc += `  ${cleanId}:\n    build:\n      context: ./${cleanId}\n      dockerfile: Dockerfile\n    container_name: ${cleanId}\n    environment:\n      PORT: 8080\n      NODE_ENV: production\n    restart: always\n    networks:\n      - omniflow-net\n\n`;
          break;

        case 'database':
          dc += `  ${cleanId}:\n    image: postgres:16-alpine\n    container_name: ${cleanId}\n    environment:\n      POSTGRES_USER: omni_admin\n      POSTGRES_PASSWORD: \${DB_PASSWORD:-secure_pass_2026}\n      POSTGRES_DB: app_db\n    volumes:\n      - pgdata_${cleanId}:/var/lib/postgresql/data\n    networks:\n      - omniflow-net\n\n`;
          break;

        case 'cache':
          dc += `  ${cleanId}:\n    image: redis:7.2-alpine\n    container_name: ${cleanId}\n    command: redis-server --appendonly yes --maxmemory 512mb\n    volumes:\n      - redisdata_${cleanId}:/data\n    networks:\n      - omniflow-net\n\n`;
          break;

        case 'queue':
          dc += `  ${cleanId}:\n    image: confluentinc/cp-kafka:7.5.0\n    container_name: ${cleanId}\n    environment:\n      KAFKA_NODE_ID: 1\n      KAFKA_LISTENER_SECURITY_PROTOCOL_MAP: 'CONTROLLER:PLAINTEXT,PLAINTEXT:PLAINTEXT'\n      KAFKA_ADVERTISED_LISTENERS: 'PLAINTEXT://${cleanId}:9092'\n    networks:\n      - omniflow-net\n\n`;
          break;

        case 'vector_db':
          dc += `  ${cleanId}:\n    image: milvusdb/milvus:v2.3.4\n    container_name: ${cleanId}\n    environment:\n      ETCD_ENDPOINTS: etcd:2379\n      MINIO_ADDRESS: minio:9000\n    networks:\n      - omniflow-net\n\n`;
          break;

        case 'blob_store':
          dc += `  ${cleanId}:\n    image: minio/minio:RELEASE.2023-11-20T22-40-07Z\n    container_name: ${cleanId}\n    command: server /data --console-address ":9001"\n    networks:\n      - omniflow-net\n\n`;
          break;

        default:
          dc += `  ${cleanId}:\n    image: alpine:latest\n    container_name: ${cleanId}\n    command: ["sleep", "infinity"]\n    networks:\n      - omniflow-net\n\n`;
          break;
      }
    });

    dc += `networks:\n  omniflow-net:\n    driver: bridge\n\nvolumes:\n`;
    nodes.filter(n => n.type === 'database' || n.type === 'cache').forEach(n => {
      const cleanId = n.id.replace(/[^a-zA-Z0-9_]/g, '-').toLowerCase();
      dc += `  ${n.type === 'database' ? 'pgdata' : 'redisdata'}_${cleanId}:\n`;
    });

    return dc;
  }

  /**
   * Generates Kubernetes Manifests (YAML)
   */
  static generateKubernetes(nodes, connections) {
    let k8s = `# =========================================================================\n`;
    k8s += `# Kubernetes Production Manifests — Generated by OmniFlow Studio (WebMCP)\n`;
    k8s += `# =========================================================================\n\n`;
    k8s += `apiVersion: v1\nkind: Namespace\nmetadata:\n  name: omniflow-prod\n---\n`;

    nodes.filter(n => n.type === 'service' || n.type === 'gateway' || n.type === 'ai_model').forEach(node => {
      const cleanId = node.id.replace(/[^a-zA-Z0-9_]/g, '-').toLowerCase();
      k8s += `apiVersion: apps/v1\nkind: Deployment\nmetadata:\n  name: ${cleanId}\n  namespace: omniflow-prod\n  labels:\n    app: ${cleanId}\nspec:\n  replicas: 3\n  selector:\n    matchLabels:\n      app: ${cleanId}\n  template:\n    metadata:\n      labels:\n        app: ${cleanId}\n    spec:\n      containers:\n      - name: ${cleanId}\n        image: ghcr.io/omniflow/${cleanId}:latest\n        ports:\n        - containerPort: 8080\n        resources:\n          limits:\n            cpu: "1000m"\n            memory: "1024Mi"\n          requests:\n            cpu: "250m"\n            memory: "256Mi"\n        livenessProbe:\n          httpGet:\n            path: /health\n            port: 8080\n          initialDelaySeconds: 15\n          periodSeconds: 10\n---\n`;
      k8s += `apiVersion: v1\nkind: Service\nmetadata:\n  name: ${cleanId}-svc\n  namespace: omniflow-prod\nspec:\n  type: ClusterIP\n  selector:\n    app: ${cleanId}\n  ports:\n  - port: 80\n    targetPort: 8080\n---\n`;
    });

    return k8s;
  }

  /**
   * Generates TypeScript Architecture Object
   */
  static generateTypeScript(nodes, connections) {
    const data = {
      version: '2.0.0',
      generatedAt: new Date().toISOString(),
      generator: 'OmniFlow WebMCP Engine',
      systemTopology: {
        totalNodes: nodes.length,
        totalConnections: connections.length,
        nodes: nodes.map(n => ({
          id: n.id,
          label: n.label,
          type: n.type,
          status: n.status,
          telemetry: { cpu: n.cpu, memory: n.memory }
        })),
        connections: connections.map(c => ({
          id: c.id,
          from: c.from,
          to: c.to,
          protocol: c.protocol,
          latency: c.latency,
          throughput: c.throughput
        }))
      }
    };

    return `// =========================================================================\n// TypeScript System Topology Manifest — Generated by OmniFlow Studio\n// =========================================================================\n\nexport interface ArchitectureTopology {\n  version: string;\n  generatedAt: string;\n  generator: string;\n  systemTopology: {\n    totalNodes: number;\n    totalConnections: number;\n    nodes: Array<{\n      id: string;\n      label: string;\n      type: string;\n      status: string;\n      telemetry: { cpu?: number; memory?: number };\n    }>;\n    connections: Array<{\n      id: string;\n      from: string;\n      to: string;\n      protocol: string;\n      latency?: string;\n      throughput?: string;\n    }>;\n  };\n}\n\nexport const productionArchitecture: ArchitectureTopology = ${JSON.stringify(data, null, 2)};\n`;
  }
}
